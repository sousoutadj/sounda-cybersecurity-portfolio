function setLanguage(lang){
  if (!translations[lang]) lang = 'en';
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const value = translations[lang][key];
    if (typeof value === 'string') el.textContent = value;
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', String(active));
  });

  const cvPath = lang === 'fr' ? 'assets/CV_Sounda_Francais.pdf' : 'assets/CV_Sounda_English.pdf';
  document.querySelectorAll('.cv-link').forEach(link => link.setAttribute('href', cvPath));

  document.querySelectorAll('[data-img-en][data-img-fr]').forEach(img => {
    img.src = lang === 'fr' ? img.dataset.imgFr : img.dataset.imgEn;
  });

  document.title = lang === 'fr'
    ? 'Sounda Abdelkerim Ahmat | Portfolio Cybersécurité'
    : 'Sounda Abdelkerim Ahmat | Cybersecurity Portfolio';

  const metaDescription = document.querySelector('meta[name="description"]');
  if (metaDescription) {
    metaDescription.setAttribute('content', lang === 'fr'
      ? 'Portfolio cybersécurité de Sounda Abdelkerim Ahmat — Audit SSI, GRC, sécurité de l’information et projets techniques.'
      : 'Cybersecurity portfolio of Sounda Abdelkerim Ahmat — IT Security Audit, GRC, information security and technical cybersecurity projects.');
  }

  localStorage.setItem('soundaPortfolioLang', lang);
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});

